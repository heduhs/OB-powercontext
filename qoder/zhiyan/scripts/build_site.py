#!/usr/bin/env python3
"""Build the deployable Qoder Site from the repository sources.

    python scripts/build_site.py

Reads
    frontend/                     page source (html/css/js/img)
    backend/sample_data.py        corpus shown by the site's demo mode
    records/verification*.json    measured retrieval numbers shown on the page
    records/site-analytics.json   optional PV/UV snapshot (see README)
Writes
    site/                         the exact directory published to Qoder Sites

Keeping the published site generated from the repository is deliberate: the
reviewer can diff what is live against what is committed.
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.sample_data import all_documents  # noqa: E402

PLACEHOLDER_DEFAULTS = {
    "__SEM_VECTOR__": "—", "__SEM_FULLTEXT__": "—", "__SEM_HYBRID__": "—",
    "__SEM_RRF50__": "—", "__SEM_GAIN__": "—",
    "__OFF_VECTOR__": "—", "__OFF_FULLTEXT__": "—", "__OFF_HYBRID__": "—", "__OFF_GAIN__": "—",
    "__PV__": "统计中", "__UV__": "统计中", "__WINDOW__": "近 30 天",
    "__CORPUS__": "48", "__RECALL__": "—",
}


def load_json(path: Path):
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def fmt(value) -> str:
    return "—" if value is None else f"{value:.4f}"


def bench_values(semantic, offline) -> dict:
    out = {}
    if semantic:
        avg = semantic["hybrid"]["average_recall_at_5"]
        sweep = semantic["hybrid"]["fusion_sweep"]
        rrf50 = next((s["recall_at_5"] for s in sweep
                      if s["fuse"] == "rrf" and abs(s["w_vec"] - 0.5) < 1e-9), None)
        out["__SEM_VECTOR__"] = fmt(avg["vector"])
        out["__SEM_FULLTEXT__"] = fmt(avg["fulltext"])
        out["__SEM_HYBRID__"] = fmt(avg["hybrid"])
        out["__SEM_RRF50__"] = fmt(rrf50)
        gain = round(avg["hybrid"] - max(avg["vector"], avg["fulltext"]), 4)
        out["__SEM_GAIN__"] = f"+{gain:.4f}"
        out["__RECALL__"] = fmt(avg["hybrid"])
    if offline:
        avg = offline["hybrid"]["average_recall_at_5"]
        out["__OFF_VECTOR__"] = fmt(avg["vector"])
        out["__OFF_FULLTEXT__"] = fmt(avg["fulltext"])
        out["__OFF_HYBRID__"] = fmt(avg["hybrid"])
        gain = round(avg["hybrid"] - max(avg["vector"], avg["fulltext"]), 4)
        out["__OFF_GAIN__"] = (f"+{gain:.4f}" if gain >= 0 else f"{gain:.4f}")
    return out


def main() -> int:
    src, out = ROOT / "frontend", ROOT / "site"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    for item in src.iterdir():
        if item.name == "app.js" or item.is_dir():
            shutil.copytree(item, out / item.name) if item.is_dir() else shutil.copy2(item, out / item.name)
        elif item.suffix in {".html", ".css"}:
            shutil.copy2(item, out / item.name)

    docs = all_documents()
    (out / "corpus.js").write_text(
        "// Generated by scripts/build_site.py from backend/sample_data.py — do not edit by hand.\n"
        "window.ZHIYAN_CORPUS = " + json.dumps(docs, ensure_ascii=False, indent=0).replace("\n", " ") + ";\n",
        encoding="utf-8")

    semantic = load_json(ROOT / "records" / "verification.json")
    offline = load_json(ROOT / "records" / "verification-offline.json")
    analytics = load_json(ROOT / "records" / "site-analytics.json")

    values = dict(PLACEHOLDER_DEFAULTS)
    values.update(bench_values(semantic, offline))
    values["__CORPUS__"] = str(len(docs))
    if analytics:
        values["__PV__"] = str(analytics.get("pv", values["__PV__"]))
        values["__UV__"] = str(analytics.get("uv", values["__UV__"]))
        values["__WINDOW__"] = str(analytics.get("window", values["__WINDOW__"]))

    index = (out / "index.html").read_text(encoding="utf-8")
    missing = [k for k in PLACEHOLDER_DEFAULTS if k in index]
    for key, val in values.items():
        index = index.replace(key, val)
    leftover = [k for k in missing if k in index]
    if leftover:
        print("未替换的占位符:", leftover)
    (out / "index.html").write_text(index, encoding="utf-8")

    files = sorted(p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file())
    total = sum((out / f).stat().st_size for f in files)
    print(f"site/ 已生成：{len(files)} 个文件，{total/1024:.1f} KB")
    for f in files:
        print("  -", f)
    print("语料注入：", len(docs), "条；语义实测：",
          "有" if semantic else "缺 verification.json", "；离线实测：",
          "有" if offline else "缺 verification-offline.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
